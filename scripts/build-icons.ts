/* oxlint-disable no-await-in-loop */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

import { camelCase } from "./lib/icons.ts"

const extensionRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const iconsDirectory = path.join(extensionRoot, "src", "assets", "icons")
const outputPath = path.join(extensionRoot, "src", "lib", "icons.ts")

export async function buildIcons(): Promise<number> {
    const files = (await readdir(iconsDirectory)).filter((file) => file.endsWith(".svg")).sort()
    const entries: string[] = []
    for (const file of files) {
        const source = await readFile(path.join(iconsDirectory, file), "utf8")
        entries.push(`    ${camelCase(file.slice(0, -4))}: ${JSON.stringify(source.trim())},`)
    }

    const template = `// This file is generated by scripts/build-icons.ts — do not edit directly.

export const icons: Record<string, string> = {
${entries.join("\n")}
}

export function icon(name: string): string {
    return icons[name] ?? ""
}
`

    await mkdir(path.dirname(outputPath), { recursive: true })
    await writeFile(outputPath, template)
    console.log(`Wrote ${entries.length} icons to ${path.relative(extensionRoot, outputPath)}`)
    return entries.length
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
    buildIcons().catch((error: unknown) => {
        console.error(error)
        process.exitCode = 1
    })
}
