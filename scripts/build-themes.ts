/* oxlint-disable no-await-in-loop */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

import {
    cssDeclarationLines,
    CURATED_DARK,
    CURATED_LIGHT,
    slug,
    type ThemeEntry,
    type ThemeMode,
    type ThemeVariables,
    translateTheme,
} from "./lib/themes.ts"

const extensionRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const themesDirectory = path.join(extensionRoot, "src", "data", "themes")
const stylesDirectory = path.join(extensionRoot, "src", "styles")

export interface Theme {
    id: string
    name: string
    mode: string
    accent: string
    bg: string
    fg: string
}

interface ResolvedTheme extends Theme {
    variables: ThemeVariables
}

// Shadow DOM custom properties: the attribute selector matches the options page's `html` element
// and, inside a shadow root, the host element carrying the attribute.
function toCss(theme: ResolvedTheme): string {
    return `[data-datalith-theme="${theme.id}"] {\n\tcolor-scheme: ${theme.mode};\n${cssDeclarationLines(
        theme.variables,
    )}\n}\n`
}

function defaultBlocks(theme: ResolvedTheme): string {
    const body = `\tcolor-scheme: ${theme.mode};\n${cssDeclarationLines(theme.variables)}`
    return `:root {\n${body}\n}\n\n:host {\n${body}\n}\n`
}

async function resolveThemes(): Promise<ResolvedTheme[]> {
    const files = (await readdir(themesDirectory)).filter((file) => file.endsWith(".json"))
    const themes: ResolvedTheme[] = []
    for (const file of files) {
        const data = JSON.parse(await readFile(path.join(themesDirectory, file), "utf8")) as {
            themes?: ThemeEntry[]
        }
        for (const entry of data.themes ?? []) {
            const explicitMode: ThemeMode | null =
                entry.mode === "dark" ? "dark" : entry.mode === "light" ? "light" : null
            const mode: ThemeMode | null =
                explicitMode ??
                (CURATED_DARK.includes(entry.name)
                    ? "dark"
                    : CURATED_LIGHT.includes(entry.name)
                      ? "light"
                      : null)
            if (!mode) continue
            const id = slug(entry.name)
            themes.push({
                id,
                name: entry.name,
                mode,
                accent: "",
                bg: "",
                fg: "",
                variables: translateTheme(entry, mode),
            })
        }
    }

    themes.sort((a, b) => {
        if (a.mode !== b.mode) return a.mode === "light" ? -1 : 1
        return a.name.localeCompare(b.name)
    })

    for (const theme of themes) {
        theme.accent = theme.variables.accent
        theme.bg = theme.variables.bg
        theme.fg = theme.variables.fg
    }
    return themes
}

export async function buildThemes(): Promise<Theme[]> {
    const themes = await resolveThemes()
    const defaultTheme = themes.find((theme) => theme.id === "datalith-light")
    if (!defaultTheme) throw new Error("Datalith Light theme is missing from the curated set")
    const css = [
        "/* This file is generated by scripts/build-themes.ts — do not edit directly. */",
        defaultBlocks(defaultTheme),
        ...themes.map((theme) => toCss(theme)),
    ].join("\n")

    await mkdir(stylesDirectory, { recursive: true })
    await writeFile(path.join(stylesDirectory, "themes.css"), css)
    await writeFile(
        path.join(extensionRoot, "src", "data", "themes.json"),
        `${JSON.stringify(
            themes.map(({ variables, ...theme }) => theme),
            null,
            2,
        )}\n`,
    )
    console.log(`Wrote ${themes.length} themes to src/styles/themes.css and src/data/themes.json`)
    return themes.map(({ variables, ...theme }) => theme)
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
    buildThemes().catch((error: unknown) => {
        console.error(error)
        process.exitCode = 1
    })
}
